import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../..');
const reportDir = path.join(repoRoot, 'Test Report - Group08');
const inputFile = path.join(reportDir, 'group08-results.json');
if (!fs.existsSync(inputFile)) {
  console.error('CHUA CO JSON KET QUA: hay chay npm test / scripts/run-group-suite.ps1 tren may co mang va Chromium.');
  process.exitCode = 2;
} else {
  const report = JSON.parse(fs.readFileSync(inputFile, 'utf8'));
  const stats = report.stats ?? {};
  const perFeature = new Map();
  const failures = [];
  const skipped = [];
  const all = [];
  const redact = (s) => String(s ?? '').replace(/\b0\d{9,10}\b/g, '[REDACTED_PHONE]').replace(/\s+/g, ' ').slice(0, 260);
  const escaped = (s) => redact(s).replace(/\|/g, '\\|');
  const feature = (s) => /DDV_(F\d\d)_\d{3}/.exec(s)?.[1] || 'UNKNOWN';
  const walk = (suite, file = '') => {
    const actualFile = suite.file || file;
    for (const spec of suite.specs || []) {
      for (const t of spec.tests || []) {
        const title = `${spec.title || ''}`;
        const id = /DDV_F\d\d_\d{3}/.exec(title)?.[0] || 'NO_ID';
        const feat = feature(id);
        const hist = t.results || [];
        const last = hist.at(-1) || {};
        const lastStatus = last.status || 'unknown';
        const outcome = t.status === 'skipped' || lastStatus === 'skipped' || (!hist.length && spec.ok === false)
          ? 'Skipped'
          : t.status === 'unexpected' || lastStatus === 'failed' || lastStatus === 'timedOut' || lastStatus === 'interrupted'
            ? 'Failed'
            : t.status === 'flaky' ? 'Flaky'
            : lastStatus === 'passed' ? 'Passed' : 'Unknown';
        const row = { id, title, feature: feat, file: actualFile || spec.file || '', outcome, duration: hist.reduce((n,r)=>n+(r.duration||0),0), last };
        all.push(row);
        if (!perFeature.has(feat)) perFeature.set(feat, { Passed:0,Failed:0,Skipped:0,Flaky:0,Unknown:0 });
        perFeature.get(feat)[outcome]++;
        if (outcome === 'Failed') failures.push(row);
        if (outcome === 'Skipped') skipped.push(row);
      }
    }
    for (const child of suite.suites || []) walk(child, actualFile);
  };
  for (const suite of report.suites || []) walk(suite);
  const totals = Object.values(Object.fromEntries(perFeature)).reduce((acc,s) => {
    for (const [k,v] of Object.entries(s)) acc[k]=(acc[k]||0)+v;
    return acc;
  },{Passed:0,Failed:0,Skipped:0,Flaky:0,Unknown:0});
  const start = stats.startTime || report.startTime || '(not provided)';
  const durationMs = Number(stats.duration || report.duration || 0);
  const lines = [
    '# Group08 – Test Execution Report (AUTO-GENERATED FROM PLAYWRIGHT JSON)',
    '',
    `- **Source:** \`group08-results.json\` (generated by real Playwright run).`,
    `- **Start:** ${escaped(start)} | **Duration:** ${(durationMs/1000).toFixed(2)} seconds`,
    `- **Tests collected in JSON:** ${all.length}`,
    `- **Passed:** ${totals.Passed} | **Failed:** ${totals.Failed} | **Skipped:** ${totals.Skipped} | **Flaky:** ${totals.Flaky} | **Unknown:** ${totals.Unknown}`,
    '',
    '## By function',
    '',
    '| Function | Passed | Failed | Skipped | Flaky | Unknown | Total |',
    '|---|---:|---:|---:|---:|---:|---:|',
  ];
  for (const [k,v] of [...perFeature].sort(([a],[b])=>a.localeCompare(b))) lines.push(`| ${k} | ${v.Passed} | ${v.Failed} | ${v.Skipped} | ${v.Flaky} | ${v.Unknown} | ${Object.values(v).reduce((a,b)=>a+b,0)} |`);
  lines.push('', '## Important context', '',
    '- Đây là kết quả của **lượt chạy sinh ra JSON**, không phải kết quả hợp nhất từ nhiều lần chạy riêng.',
    '- Test có lỗi server nhưng chỉ assert UI vẫn có thể Passed; cần đối chiếu Expected Result và bug log.',
    '- Nếu `Failed > 0`, giữ nguyên lỗi thực tế; không đổi trạng thái để làm đẹp báo cáo.',
    '- `Skipped` phải có giải thích fixture/điều kiện trong report hoặc source.',
    '- Flaky phải xác minh qua nhiều lần chạy có kiểm soát; Playwright retries=0 không tự chứng minh flaky.',
    '',
    '## Files',
    '',
    '- HTML: `html-report/index.html`',
    '- XML: `group08-junit.xml`',
    '- Raw JSON: `group08-results.json`',
    '- Failures: `Defect_Log.md`',
  );
  fs.writeFileSync(path.join(reportDir,'GroupSuite_Summary.md'),lines.join('\n')+'\n','utf8');
  const bug = [
    '# Group08 – Failed test cases recorded in executed suite',
    '',
    '> Các dòng được trích từ Playwright, chưa mặc nhiên là các **bug độc lập**. Cần triage nguyên nhân gốc.',
    '',
    '| Test ID | File | Runtime (ms) | First error text |',
    '|---|---|---:|---|',
  ];
  for (const f of failures) {
    const msg = f.last.errors?.[0]?.message || f.last.error?.message || f.last.error?.value || '(no structured error message)';
    bug.push(`| ${f.id} | ${escaped(path.basename(f.file))} | ${f.duration} | ${escaped(msg)} |`);
  }
  if (!failures.length) bug.push('| (No recorded failures) | | | |');
  bug.push('', '## Triage required', '',
    '1. Re-run a failed case in isolation and compare traces/screenshots.',
    '2. Distinguish real website defects, script locator errors, expired fixtures and transient network failures.',
    '3. Record root-cause grouping, severity, reproducibility and recommended fix in review notes.',
    '', '## Skipped tests', '',
    ...skipped.map(s=>`- ${s.id} (${escaped(s.title)})`),
  );
  fs.writeFileSync(path.join(reportDir,'Defect_Log.md'),bug.join('\n')+'\n','utf8');
  console.log(`Report created: ${totals.Passed} Passed, ${totals.Failed} Failed, ${totals.Skipped} Skipped, ${totals.Flaky} Flaky, ${totals.Unknown} Unknown.`);
}
